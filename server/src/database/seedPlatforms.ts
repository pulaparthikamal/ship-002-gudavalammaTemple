const seed = async () => {
  try {
    await connectDB();
    logger.info('Connected to DB for seeding platforms.');

    for (const platform of platforms) {
      await Platform.findOneAndUpdate(
        { name: platform.name },
        platform,
        { upsert: true, new: true }
      );
      logger.info(`Upserted platform: ${platform.name}`);
    }

    // Also handle legacy name 'Twitter' if it exists
    await Platform.findOneAndUpdate(
        { name: 'Twitter' },
        { active: false },
    );

    logger.info('Platform seeding finished.');
    await mongoose.connection.close();
    process.exit(0);
  } catch (error) {
    logger.error('Seeding failed:', error);
    process.exit(1);
  }
};

seed();
